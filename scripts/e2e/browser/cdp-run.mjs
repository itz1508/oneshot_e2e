const seen = new Map();
export const stageFirstSeen = {};

function recordEvent(e) {
  if (!e || !e.event_id || seen.has(e.event_id)) return false;
  seen.set(e.event_id, e);
  evidence.sse.push(e);
  console.log(
    `[evt] #${e.sequence} ${e.processor} ${e.state}` +
      (e.result ? ` result=${e.result}` : "") +
      (e.artifact_id ? ` artifact=${String(e.artifact_id).slice(0, 50)}` : "") +
      (e.message ? ` | ${String(e.message).slice(0, 100)}` : ""),
  );
  if (e.processor && !stageFirstSeen[e.processor]) {
    stageFirstSeen[e.processor] = {
      at: new Date().toISOString(),
      sequence: e.sequence,
      state: e.state,
    };
  }
  return true;
}

export async function pullNewEvents() {
  const raw = await evaluate(
    `(window.__oneshotEvents||[]).map(function(e){return JSON.stringify(e)}).join('\\n')`,
  );
  if (typeof raw !== "string" || !raw) return;
  for (const line of raw.split("\n")) {
    if (!line.trim()) continue;
    try {
      recordEvent(JSON.parse(line));
    } catch {}
  }
}

export function hasStage(name) {
  return Boolean(stageFirstSeen[name]);
}

export async function grabWindowRecords() {
  const raw = await evaluate(
    `JSON.stringify({requests:(window.__oneshotRequests||[]).map(function(r){return {url:r.url,method:r.method,status:r.status,body:(r.body||'').slice(0,4000)}}), sse:(window.__oneshotSSE||[])})`,
  );
  if (typeof raw !== "string") return;
  try {
    const parsed = JSON.parse(raw);
    evidence.requests = parsed.requests;
    evidence.sse_streams = parsed.sse;
  } catch {}
}

export function extractIds() {
  const convPost = evidence.requests.find(
    (r) => r.method === "POST" && r.url.endsWith("/api/conversations") && r.body,
  );
  if (convPost) {
    try {
      evidence.conversation_created = JSON.parse(convPost.body).conversation_id
        ? JSON.parse(convPost.body)
        : evidence.conversation_created;
    } catch {}
  }
  const convResp = evidence.requests.find(
    (r) => r.method === "POST" && r.url.endsWith("/api/conversations") && r.status === 201,
  );
  const runPost = evidence.requests.find(
    (r) => r.method === "POST" && /\/api\/conversations\/[^/]+\/run$/.test(r.url),
  );
  evidence.run_post = runPost || null;
  // response bodies are captured by the page tap (window records)
  const msgDone = seen.size ? [...seen.values()] : [];
  const runEvents = msgDone.filter((e) => e.run_id);
  evidence.run_id_extracted_from_events = runEvents.length ? runEvents[0].run_id : null;
}

export async function apiGet(path) {
  const res = await fetch(`${BASE_URL}${path}`, {
    headers: { authorization: `Bearer ${TOKEN}` },
  });
  return { status: res.status, body: res.ok ? await res.json() : null };
}

// ── observation loop ──────────────────────────────────────────────────────────
const shotTaken = {};

export async function observeUntilDone(timeoutMs = 420_000) {
  const deadline = Date.now() + timeoutMs;
  let lastSeq = 0;
  while (Date.now() < deadline) {
    await pullNewEvents();
    await resolveIdsFromPage();

    const events = evidence.sse;
    const latest = events[events.length - 1];
    const done = events.find(
      (e) => e.processor === "Done" && e.state === "COMPLETE",
    );

    // §26 live intermediate screenshots (best effort, once each)
    if (!shotTaken["03"] && hasStage("Researcher")) {
      shotTaken["03"] = true;
      await sleep(500);
      await screenshot("03-researcher-running.png");
    }
    if (
      !shotTaken["04"] &&
      (hasStage("GoalValidation") || hasStage("TripleValidation"))
    ) {
      shotTaken["04"] = true;
      await sleep(300);
      await screenshot("04-validation-running.png");
    }
    if (!shotTaken["05"] && hasStage("Builder")) {
      shotTaken["05"] = true;
      await screenshot("05-builder-running.png");
      // Builder may complete in <1s: take a second shot to catch visible state
      await sleep(700);
      await screenshot("06-builder-trace.png");
    }

    if (latest && latest.sequence > lastSeq) lastSeq = latest.sequence;
    if (done) {
      evidence.done_event = done;
      if (!shotTaken["06_done"]) {
        await sleep(2000); // let the UI render the completion message
        await screenshot("06-done.png");
        shotTaken["06_done"] = true;
      }
      return done;
    }
    if (
      events.some(
        (e) => e.state === "COMPLETE" && e.result === "ROOT_CAUSE" && e.processor === "Done",
      )
    ) {
      return null; // handled by caller via evidence
    }
    await sleep(200);
  }
  throw new Error("observation timeout before Done");
}

