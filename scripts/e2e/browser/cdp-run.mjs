export async function persistenceProof() {
  // 1. refresh the browser
  await cdp.send("Page.reload");
  await waitFor("page reload", async () =>
    (await evaluate("document.readyState")) === "complete" ? true : undefined,
  );
  await waitFor("chat input after reload", async () =>
    (await evaluate(
      `!!document.querySelector('textarea[placeholder="Message OneShot..."]')`,
    )) ? true : undefined,
  );
  await sleep(1200);
  evidence.persistence.ui_chat_after_reload = await evaluate(
    `document.body.textContent.includes('OneShot Canonical Execution Completed')`,
  );
  await screenshot("07-after-refresh.png");

  // 2. backend persistence checks
  if (evidence.run_id) {
    const snap = await apiGet(`/api/runs/${evidence.run_id}`);
    evidence.persistence.run_snapshot_status = snap.status;
    evidence.persistence.run_result = snap.body?.result;
    evidence.persistence.run_event_count = snap.body?.events?.length;
    evidence.persistence.hash_proof = snap.body?.hash_proof ?? null;
    const task = await apiGet(`/api/runs/${evidence.run_id}/task`);
    evidence.persistence.task_projection_status = task.status;
  }
  if (evidence.conversation_id) {
    const conv = await apiGet(`/api/conversations/${evidence.conversation_id}`);
    evidence.persistence.conversation_status = conv.status;
    evidence.persistence.conversation_turns = conv.body?.turns?.length;
    evidence.persistence.conversation_revision = conv.body?.intent?.revision;
  }
}

