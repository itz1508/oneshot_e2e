async function grabBackendProof() {
  if (!evidence.run_id) return;
  const snap = await apiGet(`/api/runs/${evidence.run_id}`);
  evidence.run_snapshot = snap.body;
  const sandbox = await apiGet(`/api/runs/${evidence.run_id}/sandbox`);
  evidence.sandbox_evidence = sandbox.body;
  const task = await apiGet(`/api/runs/${evidence.run_id}/task`);
  evidence.task_projection_status = task.status;
  try {
    const evFile = join(
      ROOT,
      "data",
      "task-events",
      `${evidence.run_id}.jsonl`,
    );
    if (existsSync(evFile)) {
      evidence.task_events_file = evFile;
      evidence.task_events_lines = readFileSync(evFile, "utf8").trim().split("\n").length;
    }
  } catch {}
}

